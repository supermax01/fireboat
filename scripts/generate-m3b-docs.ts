/** Behaviour of the repair helpers, measured by calling them rather than restating their constants. */
export function repairBehaviour() {
  const allReviewed = { resource: () => true, parameter: () => true };
  const scanType = Object.keys(OBSERVED_CODE_FIELDS)[0]!;
  const scan = repairForNoMatches(scanType, allReviewed, [{ name: OBSERVED_CODE_DATE_PARAMETERS[scanType]![0]!, value: 'ge2020-01-01' }]);
  if (!scan || scan.action !== 'inspect_observed_codes') throw new Error('observed-code scan repair is not produced for a reviewed type and date window');
  const tuples = Array.from({ length: 80 }, (_, i) => ({ system: 'urn:example:s', code: `c${i}` }));
  const combined = observedCodeOrValueDetailed(tuples);
  const split = splitEscapedCommaOrDetailed(Array.from({ length: 80 }, (_, i) => `x${i}`).join(','));
  return { scan, maxTuples: combined.value.split(',').length, combineTruncates: combined.truncated, maxSplitParts: split.parts.length, splitTruncates: split.truncated };
}
const REPAIR_META = { resource_type: 'Observation', parameter: 'code', allowed_max_bytes: 24576, current_max_bytes: 4096 };
const REVIEWED = { resource: () => true, parameter: () => true };
/** The repair a fault yields with every name reviewed and a larger budget available, as the gateway would build it. */
export const repairFor = (fault: string) => repairForFault(fault, REPAIR_META, REVIEWED);

