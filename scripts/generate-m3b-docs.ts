/** Strict arguments: at most `--check` once and `--root <dir>` once; anything else is a usage error before any write. */
export function parseArguments(args: readonly string[]): { check: boolean; root: string } | undefined {
  let check = false, root: string | undefined;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check' && !check) check = true;
    else if (args[i] === '--root' && root === undefined && args[i + 1] !== undefined && !args[i + 1]!.startsWith('--')) root = args[++i];
    else return undefined;
  }
  return { check, root: root ?? repository };
}

async function main(): Promise<void> {
  const parsed = parseArguments(process.argv.slice(2));
  if (!parsed) { console.error('generate-m3b-docs: usage: [--check] [--root <dir>]'); process.exit(2); }
  const { check, root } = parsed;
  // Writes stay inside <root>/docs: a symlinked docs directory or output file refuses rather than being followed.
  const linked = (path: string) => { try { return lstatSync(path).isSymbolicLink(); } catch { return false; } };
  if (linked(join(root, 'docs')) || Object.keys(GENERATED_DOCS).some(path => linked(join(root, path)))) {
    console.error('generate-m3b-docs: refusing a symlinked docs directory or output file'); process.exit(2);
  }
  const stale: string[] = [];
  for (const [path, build] of Object.entries(GENERATED_DOCS)) {
    const expected = build(), file = join(root, path);
    if (check) {
      let actual: string | undefined;
      try { actual = await readFile(file, 'utf8'); } catch { actual = undefined; }
      if (actual !== expected) stale.push(path);
    } else await writeFile(file, expected);
  }
  if (stale.length) { console.error(`generate-m3b-docs: out of sync with the code: ${stale.join(', ')}; regenerate.`); process.exit(1); }
  console.log(`generate-m3b-docs: ${Object.keys(GENERATED_DOCS).length} files ${check ? 'in sync' : 'written'}`);
}
const invoked = (() => { try { return process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; } })();
if (invoked) main().catch(error => { console.error(`generate-m3b-docs: ${error instanceof Error ? error.message : 'failed'}`); process.exit(2); });
